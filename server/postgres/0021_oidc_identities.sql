-- PostgreSQL baseline for the SQLite 0021 schema. Currency units are integer kopecks.
CREATE TABLE accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'other' CHECK (type IN ('card', 'cash', 'savings', 'other')),
  currency TEXT NOT NULL DEFAULT 'RUB',
  sort BIGINT NOT NULL DEFAULT 0,
  archived BIGINT NOT NULL DEFAULT 0,
  opening_balance BIGINT NOT NULL DEFAULT 0,
  opening_date TEXT,
  icon TEXT NOT NULL DEFAULT 'wallet',
  color TEXT NOT NULL DEFAULT '#5b6472',
  icon_image TEXT,
  connection_id BIGINT,
  bank_ref TEXT NOT NULL DEFAULT '',
  card_tails TEXT NOT NULL DEFAULT '',
  UNIQUE (user_id, name)
);
CREATE TABLE activity_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  kind TEXT NOT NULL,
  created_at TEXT NOT NULL,
  detail TEXT
);
CREATE TABLE alembic_version (
  version_num VARCHAR(32) NOT NULL,
  CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num)
);
CREATE TABLE bank_connections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  bank TEXT NOT NULL,
  kind TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'disconnected'
  CHECK (status IN ('disconnected', 'connected', 'awaiting_sms', 'error')),
  credentials_encrypted BYTEA,
  session_encrypted BYTEA,
  last_sync TEXT,
  last_error TEXT,
  pending_account_id BIGINT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE budgets (
  category_id BIGINT NOT NULL,
  year BIGINT NOT NULL,
  month BIGINT NOT NULL CHECK (month BETWEEN 1 AND 12),
  amount BIGINT NOT NULL,           -- kopecks
  PRIMARY KEY (category_id, year, month)
);
CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT NOT NULL,
  name TEXT NOT NULL,
  keywords TEXT NOT NULL DEFAULT '',
  sort BIGINT NOT NULL DEFAULT 0,
  archived BIGINT NOT NULL DEFAULT 0,
  goal_target BIGINT,
  goal_status TEXT CHECK (goal_status IN ('active', 'achieved', 'archived')),
  goal_target_date TEXT
);
CREATE TABLE category_group_types (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL UNIQUE,
  transaction_sign BIGINT NOT NULL CHECK (transaction_sign IN (-1, 1)),
  is_goal BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE category_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  name TEXT NOT NULL,
  sort BIGINT NOT NULL,
  type_id BIGINT NOT NULL,
  UNIQUE (user_id, name)
);
CREATE TABLE feature_usage (
  user_id BIGINT NOT NULL,
  feature TEXT NOT NULL,
  day TEXT NOT NULL,
  count BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, feature, day)
);
CREATE TABLE import_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT NOT NULL,
  connection_id BIGINT,
  source TEXT NOT NULL,
  inserted BIGINT NOT NULL DEFAULT 0,
  skipped BIGINT NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);
CREATE TABLE oidc_identities (
  issuer TEXT NOT NULL,
  subject TEXT NOT NULL,
  user_id BIGINT NOT NULL,
  PRIMARY KEY (issuer, subject)
);
CREATE TABLE splits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id BIGINT NOT NULL,
  category_id BIGINT NOT NULL,
  amount BIGINT NOT NULL,
  comment TEXT NOT NULL DEFAULT '',
  sort BIGINT NOT NULL DEFAULT 0,
  UNIQUE (transaction_id, sort)
);
CREATE TABLE transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  amount BIGINT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  bank_category TEXT NOT NULL DEFAULT '',
  mcc TEXT NOT NULL DEFAULT '',
  category_id BIGINT,
  account_id BIGINT NOT NULL,
  transfer_id TEXT,
  comment TEXT NOT NULL DEFAULT '',
  hash TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'import',
  batch_id BIGINT, hidden BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE transfer_rejections (
  out_tx_id BIGINT NOT NULL,
  in_tx_id BIGINT NOT NULL,
  PRIMARY KEY (out_tx_id, in_tx_id)
);
CREATE TABLE transfers (
  id TEXT PRIMARY KEY,
  user_id BIGINT,
  out_tx_id BIGINT NOT NULL UNIQUE,
  in_tx_id BIGINT NOT NULL UNIQUE,
  origin TEXT NOT NULL DEFAULT 'manual' CHECK (origin IN ('manual', 'matched')),
  out_category_id BIGINT,
  in_category_id BIGINT,
  note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL
);
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL,
  is_admin BIGINT NOT NULL DEFAULT 0,
  last_login TEXT,
  email_canonical TEXT NOT NULL DEFAULT '',
  default_account_id BIGINT
);
CREATE INDEX idx_accounts_connection ON accounts (connection_id);
CREATE INDEX idx_accounts_user ON accounts (user_id);
CREATE INDEX idx_activity_created ON activity_events (created_at);
CREATE INDEX idx_activity_user ON activity_events (user_id);
CREATE INDEX idx_batch_account ON import_batches (account_id);
CREATE INDEX idx_categories_group ON categories (group_id);
CREATE UNIQUE INDEX idx_categories_group_name ON categories (group_id, name);
CREATE INDEX idx_conn_user ON bank_connections (user_id);
CREATE INDEX idx_groups_user ON category_groups (user_id);
CREATE INDEX idx_oidc_identities_user_id ON oidc_identities (user_id);
CREATE INDEX idx_splits_category ON splits (category_id);
CREATE INDEX idx_splits_transaction ON splits (transaction_id);
CREATE INDEX idx_transfers_user ON transfers (user_id);
CREATE INDEX idx_tx_account ON transactions (account_id);
CREATE INDEX idx_tx_category ON transactions (category_id);
CREATE INDEX idx_tx_date ON transactions (date);
CREATE INDEX idx_tx_hash ON transactions (hash);
CREATE INDEX idx_usage_day ON feature_usage (day);
CREATE UNIQUE INDEX idx_users_email_canonical ON users (email_canonical);

